"""
OCR clients for local models, inference servers and cloud services.

The clients return page text through a shared result format. Server clients use
the OpenAI compatible API; Mistral accepts PDFs directly. Local clients use
Tesseract, PaddleOCR or GOT OCR when their dependencies and model files are
available. PDF rendering runs in a separate process and rejects partial output.

Usage:

    from agent.integrations.unlimited_ocr import create_ocr_client

    # Auto-selects the best available backend
    client = create_ocr_client()
    text = client.ocr_image("scan.png")

    # Force a specific backend
    from agent.integrations.unlimited_ocr import (
        UnlimitedOCRClient,   # GPU server (Unlimited-OCR / DeepSeek)
        MistralOCRClient,      # Cloud API
    )
    client = UnlimitedOCRClient(server_url="http://gpu:10000")
    client = UnlimitedOCRClient.deepseek_ocr2(server_url="http://gpu:10000")
    client = MistralOCRClient(api_key="sk-...")
"""

